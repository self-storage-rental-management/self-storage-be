CREATE TABLE IF NOT EXISTS access_credentials (
    id BINARY(16) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    reservation_id BINARY(16) NOT NULL,
    rental_id BINARY(16) NULL,
    facility_id BINARY(16) NOT NULL,
    storage_unit_id BINARY(16) NOT NULL,
    customer_id BINARY(16) NOT NULL,
    credential_type VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    reference VARCHAR(160) NOT NULL,
    secret_hash VARCHAR(64) NULL,
    issued_by BINARY(16) NOT NULL,
    issued_at TIMESTAMP(6) NOT NULL,
    revoked_by BINARY(16) NULL,
    revoked_at TIMESTAMP(6) NULL,
    note VARCHAR(1000) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_access_credential_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id),
    CONSTRAINT fk_access_credential_rental FOREIGN KEY (rental_id) REFERENCES rentals(id),
    CONSTRAINT fk_access_credential_facility FOREIGN KEY (facility_id) REFERENCES facilities(id),
    CONSTRAINT fk_access_credential_unit FOREIGN KEY (storage_unit_id) REFERENCES storage_units(id),
    CONSTRAINT fk_access_credential_customer FOREIGN KEY (customer_id) REFERENCES users(id),
    CONSTRAINT fk_access_credential_issued_by FOREIGN KEY (issued_by) REFERENCES users(id),
    CONSTRAINT fk_access_credential_revoked_by FOREIGN KEY (revoked_by) REFERENCES users(id),
    INDEX ix_access_credential_facility_status (facility_id, status),
    INDEX ix_access_credential_reservation_status (reservation_id, status),
    INDEX ix_access_credential_rental_status (rental_id, status)
) ENGINE=InnoDB;
